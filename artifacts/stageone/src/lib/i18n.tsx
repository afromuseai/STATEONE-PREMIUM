type Translations = typeof translations
type LangTranslations = Translations["en"]

interface LangContextValue {
  lang: Lang
  setLang: (l: Lang) => void
  t: LangTranslations
}

const LangContext = createContext<LangContextValue | null>(null)

const SUPPORTED_LANGS = Object.keys(translations) as Lang[]

function detectBrowserLang(): Lang {
  const candidates = navigator.languages?.length ? navigator.languages : [navigator.language]
  for (const raw of candidates) {
    const full = raw.toLowerCase()
    const base = full.split("-")[0]
    if ((SUPPORTED_LANGS as string[]).includes(base)) return base as Lang
    if (full.startsWith("zh")) return "zh"
    if (full.startsWith("pt")) return "pt"
  }
  return "en"
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const stored = localStorage.getItem("stageone-lang") as Lang | null
    if (stored && (SUPPORTED_LANGS as string[]).includes(stored)) return stored
    return detectBrowserLang()
  })

  const setLang = (l: Lang) => {
    setLangState(l)
    localStorage.setItem("stageone-lang", l)
  }

  useEffect(() => {
    const dir = RTL_LANGS.includes(lang) ? "rtl" : "ltr"
    document.documentElement.dir = dir
    document.documentElement.lang = lang
  }, [lang])

  const t = translations[lang] as unknown as LangTranslations

  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>
}

export function useLang() {
  const ctx = useContext(LangContext)
  if (!ctx) throw new Error("useLang must be used inside LangProvider")
  return ctx
}

export const LOCALE_MAP: Record<Lang, string> = {
  en: "en-US",
  es: "es-ES",
  it: "it-IT",
  fr: "fr-FR",
  pt: "pt-BR",
  de: "de-DE",
  ja: "ja-JP",
  ar: "ar-SA",
  zh: "zh-CN",
}

export function useFormatters() {
  const { lang, t } = useLang()
  const locale = LOCALE_MAP[lang]

  function formatNumber(n: number): string {
    return n.toLocaleString(locale)
  }

  function formatCompact(n: number): string {
    return new Intl.NumberFormat(locale, { notation: "compact", maximumFractionDigits: 1 }).format(n)
  }

  function formatPercent(n: number): string {
    return new Intl.NumberFormat(locale, { style: "percent", maximumFractionDigits: 0 }).format(n / 100)
  }

  function formatDate(d: string): string {
    const diff = Date.now() - new Date(d).getTime()
    const mins = Math.floor(diff / 60000)
    const hrs = Math.floor(diff / 3600000)
    const days = Math.floor(diff / 86400000)
    if (mins < 1) return t.time.justNow
    if (mins < 60) return t.time.minutesAgo.replace("{n}", String(mins))
    if (hrs < 24) return t.time.hoursAgo.replace("{n}", String(hrs))
    if (days < 7) return t.time.daysAgo.replace("{n}", String(days))
    return new Date(d).toLocaleDateString(locale, { day: "numeric", month: "short", year: "numeric" })
  }

  return { formatNumber, formatCompact, formatPercent, formatDate, locale }
}
